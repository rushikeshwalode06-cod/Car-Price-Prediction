import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
sns.set_style('darkgrid')

data = pd.read_csv('car_price_dataset (1).csv')

data

data.describe(include='all')

data.isnull()

data.isnull().sum()

data['Fuel_Type'] = data['Fuel_Type'].map({'petrol':0,'Diesel':1})
data['Transmission'] = data['Transmission'].map({'Manual':0,'Automatic':1})

data.Fuel_Type.unique

data.Transmission.unique

data

data_with_no_mv =  data.dropna(axis=0)

data_with_no_mv

data_with_no_mv.isnull().sum()

data_with_no_mv

data_with_no_mv.Car_Name.unique

data_with_no_mv = data_with_no_mv.drop('Car_Name',axis=1)

data_with_no_mv

X = data_with_no_mv.drop('Selling_Price',axis=1)

X

y = data_with_no_mv.Selling_Price

y

from sklearn.model_selection import train_test_split

X_train,X_test,y_train,y_test = train_test_split(X,y,test_size=0.2,random_state=0)

X_train.shape

X_test.shape

from sklearn.linear_model import LinearRegression

model = LinearRegression()

model.fit(X_train,y_train)

y_pred = model.predict(X_test)

y_pred

def predict_price(year, present_price, kms, fuel, transmission, owner):
    return model.predict([[year, present_price, kms, fuel, transmission, owner]])

predict_price(2018,1000000,30000,0,0,0)

predict_price(2014,1500000,10000,1,1,2)

predict_price(2026,1200000,5000,1,1,0)

